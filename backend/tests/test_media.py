@pytest.mark.skipif(shutil.which("ffmpeg") is None, reason="ffmpeg required")
def test_render_pipeline_outputs_vertical_h264_aac(tts_video, tmp_path):
    from clipper.clips.render import RenderSpec, render

    plan = ReframePlanner().plan(tts_video, 0.5, 3.5, mode="center")
    spec = RenderSpec(tts_video, tmp_path / "out.mp4", 0.5, 3.5, WORDS, {"style": "dynamic"}, plan,
                      title={"text": "Hola"}, preset="ultrafast")
    info = asyncio.run(render(spec, tmp_path / "work"))
    assert info["duration"] == pytest.approx(3.0)
    out = subprocess.run(["ffprobe", "-v", "error", "-show_entries", "stream=codec_name,width,height", "-of", "csv=p=0",
                          str(tmp_path / "out.mp4")], capture_output=True, text=True).stdout
    assert "h264,1080,1920" in out and "aac" in out


def _whisper_cached() -> bool:
    try:
        from faster_whisper.utils import download_model

        download_model("tiny", local_files_only=True)
        return True
    except Exception:
        return False


@pytest.mark.skipif(not _whisper_cached(), reason="whisper tiny model not cached (needs huggingface.co once)")
def test_streaming_asr_on_real_speech(tts_video):
    from clipper.asr.engine import WhisperEngine
    from clipper.asr.streaming import StreamingTranscriber, Transcript
    from clipper.audio.decode import decode_audio

    pcm = decode_audio(tts_video)
    tr = Transcript()
    st = StreamingTranscriber(WhisperEngine("tiny"), tr)
    for i in range(0, len(pcm), 32000):
        st.feed(pcm[i: i + 32000], 100.0 + i / 16000)
    st.flush()
    assert st.wait_idle(120)
    text = " ".join(w.w for w in tr.words).lower()
    assert "walking" in text and "famous" in text
    assert all(w.s >= 100.0 for w in tr.words) and tr.words == sorted(tr.words, key=lambda w: w.s)


@pytest.mark.skipif(shutil.which("ffmpeg") is None, reason="ffmpeg required")
def test_speaker_turns_separate_two_real_voices(tmp_path):
    from clipper.asr.speakers import SpeakerTracker
    from clipper.audio.decode import decode_audio

    lines = [("slt", "Welcome back to the show today."), ("rms", "Thanks for having me here."),
             ("slt", "So what happened at your first job?"), ("rms", "I was working at a small restaurant."),
             ("rms", "And then the kitchen caught fire."), ("slt", "No way, that is insane.")]
    tr, got = SpeakerTracker(), []
    for i, (voice, text) in enumerate(lines):
        wav = tmp_path / f"l{i}.wav"
        subprocess.run(["ffmpeg", "-nostdin", "-loglevel", "error", "-y", "-f", "lavfi", "-i", f"flite=text='{text}':voice={voice}",
                        "-ar", "16000", "-ac", "1", str(wav)], check=True)
        got.append(tr.assign(decode_audio(wav))[0])
    mapping: dict[str, str] = {}
    assert all(mapping.setdefault(v, g) == g for (v, _), g in zip(lines, got))
    assert len(set(got)) == 2
