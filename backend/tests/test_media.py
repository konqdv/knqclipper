WORDS = [{"w": w, "s": i * 0.4, "e": i * 0.4 + 0.35} for i, w in enumerate("so one time I was walking home and you will not believe it".split())]


def test_ass_primitives():
    assert ass_color("#FFE600") == "&H0000E6FF"
    assert ass_color("#000000", 0.5) == "&H80000000"
    assert ass_time(3725.456) == "1:02:05.46"


@pytest.mark.parametrize("style", list(PRESETS))
def test_every_caption_style_builds_valid_events(style):
    ass = CaptionRenderer().build(WORDS, offset=0.0, duration=6.0, style={"style": style},
                                  title={"text": "Story time", "duration": 2}, watermark={"text": "@me"})
    assert "[V4+ Styles]" in ass and "Style: Cap," in ass and "Style: Title," in ass
    events = [ln for ln in ass.splitlines() if ln.startswith("Dialogue: 0,")]
    assert events
    for ev in events:
        m = re.match(r"Dialogue: 0,(\d+:\d\d:\d\d\.\d\d),(\d+:\d\d:\d\d\.\d\d)", ev)
        assert m and m.group(1) <= m.group(2)
    st = resolve_style({"style": style})
    if st["mode"] == "karaoke":
        assert "\\kf" in ass
    if st["mode"] == "dynamic":
        assert ass_color(st["highlight_color"]) in ass


def test_captions_keep_words_verbatim_and_clip_to_trim():
    st = resolve_style({"style": "phrase", "uppercase": False})
    words = prepare_words(WORDS, offset=1.0, duration=2.0, style=st)
    assert all(0 <= w.start < w.end <= 2.0 for w in words)
    assert [w.text for w in words] == [w["w"] for w in WORDS if w["e"] > 1.0 and w["s"] < 3.0]
    pages = group_pages(words, max_words=3)
    assert all(len(p) <= 3 for p in pages)


def _eval_expr(expr: str, t: float) -> float:
    py = expr.replace("if(lt(t,", "(lambda c,a,b: a if c else b)((t<").replace("),", "),", 1)
    # small evaluator for the generated grammar: if(lt(t,T),A,B)
    def ev(s: str) -> float:
        s = s.strip()
        if s.startswith("if(lt(t,"):
            body = s[len("if(lt(t,"):-1]
            th, rest = body.split(")", 1)
            rest = rest[1:]
            depth, i = 0, 0
            for i, ch in enumerate(rest):
                if ch == "(":
                    depth += 1
                elif ch == ")":
                    depth -= 1
                elif ch == "," and depth == 0:
                    break
            a, b = rest[:i], rest[i + 1:]
            return ev(a) if t < float(th) else ev(b)
        return float(eval(s, {"t": t}))  # noqa: S307 - expression generated by our own code
    py  # noqa: B018
    return ev(expr)


def test_crop_expression_is_piecewise_linear():
    kf = [(0.0, 100.0), (2.0, 300.0), (2.0, 800.0), (5.0, 800.0)]
    expr = x_expression(kf)
    assert _eval_expr(expr, 0.0) == pytest.approx(100)
    assert _eval_expr(expr, 1.0) == pytest.approx(200)
    assert _eval_expr(expr, 3.0) == pytest.approx(800)  # hard cut at t=2 (speaker switch)
    assert _eval_expr(expr, 10.0) == pytest.approx(800)


def test_path_smoothing_has_deadzone_speed_limit_and_hard_cuts():
    t = np.arange(0, 10, 0.2)
    target = np.where(t < 5, 500.0, 1400.0) + np.random.default_rng(1).normal(0, 10, len(t))
    smooth = smooth_path(t, target, deadzone=50, max_speed=300, shot_breaks=[])
    assert np.max(np.abs(np.diff(smooth))) <= 300 * 0.2 + 1e-6
    assert np.std(smooth[:20]) < 5  # jitter inside the deadzone is ignored
    cut = smooth_path(t, target, deadzone=50, max_speed=300, shot_breaks=[25])
    assert cut[25] == pytest.approx(target[25])
    assert len(rdp([(x, 2 * x) for x in range(50)], 0.5)) == 2


def test_video_filters_for_each_layout():
    assert "boxblur" in video_filter(ReframePlan("fit", 1920, 1080))
    tr = video_filter(ReframePlan("track", 1920, 1080, 608, 1080, [(0, 100), (3, 400)]))
    assert "crop=608:1080" in tr and "scale=1080:1920" in tr
    sp = video_filter(ReframePlan("split", 1920, 1080, regions=[{"x": 0.8, "y": 0.0, "w": 0.2, "h": 0.3, "out_h": 730},
                                                                {"x": 0.3, "y": 0, "w": 0.5, "h": 1, "out_h": 1190}]))
    assert "vstack=inputs=2" in sp


def test_audio_features_detect_loudness_spikes():
    sr = 16000
    rng = np.random.default_rng(0)
    calm = (0.02 * rng.normal(size=sr * 60)).astype(np.float32)
    shout = (0.5 * np.sin(2 * np.pi * 330 * np.arange(sr * 2) / sr)).astype(np.float32)
    tr = FeatureTrack()
    tr.add(compute_features(np.concatenate([calm, shout, calm[: sr * 3]]), 0.0))
    ed = EmotionDetector(tr)
    val, _ = ed.quick_trigger(60, 62)
    assert val > 0.8
    assert ed.quick_trigger(30, 32)[0] < 0.5


